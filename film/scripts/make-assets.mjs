#!/usr/bin/env node
// Writes src/assets.gen.ts: the two typefaces and the film grain as base64, so a render makes no
// network request for them (on a busy machine Chrome drops requests whenever a network interface changes).
//   node scripts/make-assets.mjs
import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';

const film = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const bulk = process.env.FILM_BULK || '/bulk2/runs/cala/film';
const require = createRequire(import.meta.url);
const url = (name) => require(`@remotion/google-fonts/${name}`).getInfo().fonts.normal['400'].latin; // both are variable fonts: one file, every weight
const b64 = async (u) => {
	const r = await fetch(u);
	if (!r.ok) throw new Error(`${r.status} ${u}`);
	return Buffer.from(await r.arrayBuffer()).toString('base64');
};
const noise = fs.readFileSync(path.join(bulk, 'public/fx/noise.png')).toString('base64');
const out = `// generated by scripts/make-assets.mjs, do not edit
export const SANS_WOFF2 = '${await b64(url('SchibstedGrotesk'))}';
export const MONO_WOFF2 = '${await b64(url('JetBrainsMono'))}';
export const NOISE_PNG = '${noise}';
`;
fs.writeFileSync(path.join(film, 'src/assets.gen.ts'), out);
console.log(`src/assets.gen.ts: ${(out.length / 1024).toFixed(0)} KB`);
